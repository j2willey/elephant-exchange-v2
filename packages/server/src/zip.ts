import { crc32 } from "node:zlib";

/**
 * A .zip of these files, stored without compression: the album's JPEGs wouldn't shrink anyway, and storing
 * keeps this small enough to own. Plain ZIP (no ZIP64), so it suits albums under 4 GB and 65,535 files.
 */
export function zip(files: { name: string; data: Uint8Array }[], at: Date): Buffer {
  // MS-DOS date and time, as ZIP records them (local time, to two seconds).
  const time = (at.getHours() << 11) | (at.getMinutes() << 5) | Math.floor(at.getSeconds() / 2);
  const date = ((at.getFullYear() - 1980) << 9) | ((at.getMonth() + 1) << 5) | at.getDate();
  const UTF8_NAMES = 0x0800;

  const locals: Buffer[] = [];
  const central: Buffer[] = [];
  let offset = 0;
  for (const file of files) {
    const name = Buffer.from(file.name, "utf8");
    const crc = crc32(file.data);
    const size = file.data.length;

    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0); // local file header
    local.writeUInt16LE(20, 4); // version needed: 2.0
    local.writeUInt16LE(UTF8_NAMES, 6);
    local.writeUInt16LE(0, 8); // stored
    local.writeUInt16LE(time, 10);
    local.writeUInt16LE(date, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(size, 18);
    local.writeUInt32LE(size, 22);
    local.writeUInt16LE(name.length, 26);
    local.writeUInt16LE(0, 28); // no extra field
    locals.push(local, name, Buffer.from(file.data.buffer, file.data.byteOffset, size));

    const entry = Buffer.alloc(46);
    entry.writeUInt32LE(0x02014b50, 0); // central directory header
    entry.writeUInt16LE(20, 4); // made by: 2.0
    entry.writeUInt16LE(20, 6); // needed: 2.0
    entry.writeUInt16LE(UTF8_NAMES, 8);
    entry.writeUInt16LE(0, 10); // stored
    entry.writeUInt16LE(time, 12);
    entry.writeUInt16LE(date, 14);
    entry.writeUInt32LE(crc, 16);
    entry.writeUInt32LE(size, 20);
    entry.writeUInt32LE(size, 24);
    entry.writeUInt16LE(name.length, 28);
    // extra, comment, disk, internal and external attributes: all zero
    entry.writeUInt32LE(offset, 42);
    central.push(entry, name);

    offset += 30 + name.length + size;
  }

  const directory = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); // end of central directory
  end.writeUInt16LE(files.length, 8);
  end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(directory.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, directory, end]);
}
